<#
.SYNOPSIS
    WSL2 & Docker Desktop Network & RAM Optimizer (`.wslconfig` generator).
    Enables Windows 11 Mirrored Networking (eliminates vEthernet NAT bottleneck and prevents
    WSL2/Docker from losing internet when corporate VPNs turn on), enables DNS Tunneling
    and Auto-Proxy, and configures automatic RAM & disk reclamation (`autoMemoryReclaim=gradual`).
#>

param(
    [switch]$ApplyShutdown
)

$WslConfigPath = Join-Path $HOME ".wslconfig"
$BackupPath    = Join-Path $HOME ".wslconfig.bak"

Write-Host "================================================================" -ForegroundColor Cyan
Write-Host "   WSL2 & DOCKER DESKTOP NETWORK / RAM OPTIMIZER" -ForegroundColor Cyan
Write-Host "================================================================" -ForegroundColor Cyan

if (Test-Path $WslConfigPath) {
    Copy-Item -Path $WslConfigPath -Destination $BackupPath -Force
    Write-Host "[OK] Backed up existing .wslconfig to $BackupPath" -ForegroundColor Yellow
}

$wslContent = @"
# Generated by network-ai-optimizer v2.0
# Restores previous config from ~/.wslconfig.bak if needed

[wsl2]
# Mirrored mode shares the Windows host physical network interface directly:
# - Achieves 100% native LAN throughput inside WSL2 & Docker containers
# - Prevents WSL2 from losing connectivity when Corporate VPNs (Cisco/Fortinet/GlobalProtect/WARP) connect
networkingMode=mirrored

# Tunnel DNS requests through Windows host resolver (fixes corporate split-DNS inside Linux)
dnsTunneling=true

# Automatically sync Windows HTTP/HTTPS proxy into WSL2 environment
autoProxy=true

# Enable Windows Hyper-V firewall integration
firewall=true

[experimental]
# Automatically release cached Linux page memory back to Windows host when idle (critical for 16GB RAM PCs)
autoMemoryReclaim=gradual

# Automatically compact WSL2 virtual disk (ext4.vhdx) when files are deleted
sparseVhd=true

# Use host loopback address seamlessly between Windows and Linux
hostAddressLoopback=true
"@

Set-Content -Path $WslConfigPath -Value $wslContent -Encoding UTF8
Write-Host "[OK] Wrote optimized WSL2 configuration to: $WslConfigPath" -ForegroundColor Green
Write-Host "   -> networkingMode = mirrored (Zero-NAT overhead + Corporate VPN compatible)" -ForegroundColor Green
Write-Host "   -> dnsTunneling   = true     (Fixes corporate DNS resolution in Linux/Docker)" -ForegroundColor Green
Write-Host "   -> autoProxy      = true     (Syncs corporate proxy to WSL2)" -ForegroundColor Green
Write-Host "   -> autoMemoryReclaim = gradual (Frees vmmemWSL RAM back to Windows)" -ForegroundColor Green

if ($ApplyShutdown -and (Get-Command wsl -ErrorAction SilentlyContinue)) {
    Write-Host "Restarting WSL2 service to apply new networking mode..." -ForegroundColor Yellow
    wsl --shutdown
    Write-Host "[OK] WSL2 shutdown complete. Next WSL/Docker launch will use Mirrored Networking!" -ForegroundColor Green
} else {
    Write-Host "[INFO] Run 'wsl --shutdown' when ready to apply the new .wslconfig settings." -ForegroundColor Cyan
}
